export function getProduct(id: string): Product {
  const product = PRODUCTS.find((p) => p.id === id);
  if (!product) throw new Error(`Unknown product id: ${id}`);
  return product;
}

export function findProduct(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id === id);
}

export function relatedProducts(product: Product, count = 4): Product[] {
  return PRODUCTS.filter((p) => p.id !== product.id && p.category === product.category)
    .sort((a, b) => b.popularity - a.popularity)
    .slice(0, count);
}

/** A product bought directly from the marketplace (not pulled from a box)
 * still needs to fit the Collection's Item shape. Box role/odds are
 * meaningless outside a box, so they're neutral placeholders here and never
 * surfaced in the UI for marketplace-sourced inventory. */
export function productToItem(product: Product): Item {
  return {
    id: product.id,
    name: product.name,
    brandId: product.brandId,
    category: product.category,
    subtype: product.subtype,
    renderShape: product.renderShape,
    marketTier: product.marketTier,
    chaseTier: "break_even",
    marketValue: product.marketValue,
    buybackValue: buybackValue(product),
    odds: 0,
    flavorOrEdition: product.variant,
    blurb: product.blurb,
  };
}
